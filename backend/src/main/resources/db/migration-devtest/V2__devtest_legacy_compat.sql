-- =====================================================================================
-- V2__devtest_legacy_compat.sql — Compatibilidade de schema APENAS para dev/test.
--
-- Enquanto as entidades JPA legadas (Usuario, Protocolo, LogAtividade) ainda estão mapeadas
-- (remoção é escopo do Sprint 2 / task 2.10), o Hibernate com ddl-auto=validate exige que
-- as tabelas tb_usuario / tb_protocolos / tb_log_atividade existam. Esta migração cria essas
-- tabelas de forma COMPATÍVEL com o mapeamento legado, para que `validate` passe.
--
-- ESCOPO: dev/test SOMENTE. Esta migração vive em `classpath:db/migration-devtest`, que é
-- adicionada a `spring.flyway.locations` apenas em dev e no ambiente de teste. PRODUÇÃO usa
-- somente `classpath:db/migration` (não aplica esta migração), mantendo o schema de produção
-- limpo (Design §10; task 0.3.8). Nunca apaga/altera o banco legado original ou seus dados.
--
-- Tipos conforme o mapeamento Hibernate atual das entidades legadas:
--   * PKs IDENTITY -> BIGINT GENERATED BY DEFAULT AS IDENTITY
--   * String sem @Column(length) -> VARCHAR(255)
--   * enums @Enumerated(STRING) -> VARCHAR(255)
--   * int primitivos -> INT NOT NULL
--   * LocalDateTime -> TIMESTAMP (without time zone)
-- =====================================================================================

-- tb_usuario (entidade legada Usuario; conflita identidade + personagem + progressão).
CREATE TABLE tb_usuario (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(255),
    classe                VARCHAR(255),
    nivel                 INT          NOT NULL,
    xp_atual              INT          NOT NULL,
    xp_para_proximo_nivel INT          NOT NULL,
    moedas                INT          NOT NULL,
    forca                 INT          NOT NULL,
    destreza              INT          NOT NULL,
    intelecto             INT          NOT NULL,
    carisma               INT          NOT NULL,
    constituicao          INT          NOT NULL,
    hp_atual              INT          NOT NULL,
    max_hp                INT          NOT NULL,
    mp_atual              INT          NOT NULL,
    max_mp                INT          NOT NULL
);

-- tb_protocolos (entidade legada Protocolo).
CREATE TABLE tb_protocolos (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(255),
    icone           VARCHAR(255),
    cor             VARCHAR(255),
    descricao       VARCHAR(255),
    atributo        VARCHAR(255),
    dificuldade     VARCHAR(255),
    duracao_minutos INT          NOT NULL,
    usuario_id      BIGINT,
    CONSTRAINT fk_tb_protocolos_usuario FOREIGN KEY (usuario_id)
        REFERENCES tb_usuario (id)
);

-- tb_log_atividade (entidade legada LogAtividade; usuario_id NOT NULL).
CREATE TABLE tb_log_atividade (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_missao     VARCHAR(255),
    icone           VARCHAR(255),
    xp_ganho        INT          NOT NULL,
    duracao_minutos INT          NOT NULL,
    data_hora       TIMESTAMP,
    usuario_id      BIGINT       NOT NULL,
    CONSTRAINT fk_tb_log_atividade_usuario FOREIGN KEY (usuario_id)
        REFERENCES tb_usuario (id)
);
