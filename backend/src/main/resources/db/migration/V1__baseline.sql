-- =====================================================================================
-- V1__baseline.sql — Baseline do schema LumeOS (banco/schema NOVO e VAZIO).
--
-- Cria as 10 tabelas do schema alvo com constraints, índices e tipos conforme o Design
-- §9 (Modelo relacional PostgreSQL) e §10 (Estratégia de Flyway). Esta migração NUNCA é
-- aplicada sobre o banco de desenvolvimento legado (que contém tb_*); o LumeOS parte de
-- um schema vazio (Design §10.3). Nenhuma tabela tb_* é criada ou removida aqui.
--
-- Convenções de tempo (Design §9.2):
--   * created_at / updated_at / data_hora  -> TIMESTAMPTZ (OffsetDateTime/Instant)
--   * data_inicio / data_fim               -> DATE (LocalDate)
-- PKs: BIGINT GENERATED BY DEFAULT AS IDENTITY.
-- =====================================================================================

-- -------------------------------------------------------------------------------------
-- users — identidade (sem dados de personagem/RPG).
-- email único case-insensitive via índice funcional UNIQUE (lower(email)) (Design §9.2).
-- password_hash dimensionado para BCrypt (60 chars; coluna 72 por margem).
-- -------------------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(72)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL
);

-- Unicidade case-insensitive de e-mail (REQ-001/REQ-002).
CREATE UNIQUE INDEX ux_users_lower_email ON users (lower(email));

-- -------------------------------------------------------------------------------------
-- game_profiles — perfil de jogo separado da identidade.
-- user_id UNIQUE (User 1->0..1 GameProfile); version BIGINT NOT NULL (locking otimista).
-- -------------------------------------------------------------------------------------
CREATE TABLE game_profiles (
    id                    BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT  NOT NULL,
    classe                VARCHAR(20)  NOT NULL,
    nivel                 INT     NOT NULL,
    xp_atual              INT     NOT NULL,
    xp_para_proximo_nivel INT     NOT NULL,
    moedas                INT     NOT NULL,
    forca                 INT     NOT NULL,
    destreza              INT     NOT NULL,
    intelecto             INT     NOT NULL,
    carisma               INT     NOT NULL,
    constituicao          INT     NOT NULL,
    hp_atual              INT     NOT NULL,
    max_hp                INT     NOT NULL,
    mp_atual              INT     NOT NULL,
    max_mp                INT     NOT NULL,
    version               BIGINT  NOT NULL,
    CONSTRAINT fk_game_profiles_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ux_game_profiles_user_id UNIQUE (user_id)
);

-- -------------------------------------------------------------------------------------
-- households — grupo compartilhado.
-- -------------------------------------------------------------------------------------
CREATE TABLE households (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL
);

-- -------------------------------------------------------------------------------------
-- household_members — vínculo User <-> Household.
-- user_id UNIQUE é a GUARDA DO MVP (no máximo 1 Household por User) (Design §9.2).
-- -------------------------------------------------------------------------------------
CREATE TABLE household_members (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT      NOT NULL,
    user_id      BIGINT      NOT NULL,
    papel        VARCHAR(20) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_household_members_household FOREIGN KEY (household_id)
        REFERENCES households (id) ON DELETE CASCADE,
    CONSTRAINT fk_household_members_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ux_household_members_user_id UNIQUE (user_id)
);

CREATE INDEX ix_household_members_household_id ON household_members (household_id);

-- -------------------------------------------------------------------------------------
-- household_invites — convites; persiste SOMENTE o hash SHA-256 (char(64)) (Design §9.1).
-- -------------------------------------------------------------------------------------
CREATE TABLE household_invites (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id      BIGINT      NOT NULL,
    invite_token_hash CHAR(64)    NOT NULL,
    expires_at        TIMESTAMPTZ NOT NULL,
    consumed_at       TIMESTAMPTZ,
    created_by        BIGINT      NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_household_invites_household FOREIGN KEY (household_id)
        REFERENCES households (id) ON DELETE CASCADE,
    CONSTRAINT fk_household_invites_created_by FOREIGN KEY (created_by)
        REFERENCES users (id),
    CONSTRAINT ux_household_invites_token_hash UNIQUE (invite_token_hash)
);

CREATE INDEX ix_household_invites_household_id ON household_invites (household_id);

-- -------------------------------------------------------------------------------------
-- habits — hábitos por usuário (ownership).
-- -------------------------------------------------------------------------------------
CREATE TABLE habits (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    nome            VARCHAR(100) NOT NULL,
    icone           VARCHAR(50),
    cor             VARCHAR(30),
    descricao       VARCHAR(500),
    atributo        VARCHAR(20)  NOT NULL,
    dificuldade     VARCHAR(20)  NOT NULL,
    duracao_minutos INT          NOT NULL,
    CONSTRAINT fk_habits_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_habits_user_id ON habits (user_id);

-- -------------------------------------------------------------------------------------
-- activity_logs — histórico snapshot. habit_id NULLABLE ON DELETE SET NULL: excluir um
-- Habit NÃO apaga o histórico (Design §9.2). data_hora TIMESTAMPTZ.
-- -------------------------------------------------------------------------------------
CREATE TABLE activity_logs (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    habit_id        BIGINT,
    nome_missao     VARCHAR(100) NOT NULL,
    icone           VARCHAR(50),
    xp_ganho        INT          NOT NULL,
    duracao_minutos INT          NOT NULL,
    data_hora       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_activity_logs_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_activity_logs_habit FOREIGN KEY (habit_id)
        REFERENCES habits (id) ON DELETE SET NULL
);

CREATE INDEX ix_activity_logs_user_id ON activity_logs (user_id);
CREATE INDEX ix_activity_logs_user_data_hora ON activity_logs (user_id, data_hora DESC);

-- -------------------------------------------------------------------------------------
-- shopping_lists — listas do household. No máximo UMA ativa por household via índice
-- único PARCIAL em (household_id) WHERE active = true (Design §9.2).
-- -------------------------------------------------------------------------------------
CREATE TABLE shopping_lists (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT       NOT NULL,
    nome         VARCHAR(100) NOT NULL,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_shopping_lists_household FOREIGN KEY (household_id)
        REFERENCES households (id) ON DELETE CASCADE
);

CREATE INDEX ix_shopping_lists_household_id ON shopping_lists (household_id);
CREATE UNIQUE INDEX ux_shopping_lists_active_por_household
    ON shopping_lists (household_id)
    WHERE active = TRUE;

-- -------------------------------------------------------------------------------------
-- shopping_items — itens da lista. Sem household_id (derivado via shopping_list_id).
-- quantidade NUMERIC(12,3) (BigDecimal). completed_by NULLABLE (Design §9.1).
-- -------------------------------------------------------------------------------------
CREATE TABLE shopping_items (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shopping_list_id BIGINT        NOT NULL,
    nome             VARCHAR(120)  NOT NULL,
    quantidade       NUMERIC(12,3) NOT NULL,
    unidade          VARCHAR(40),
    categoria        VARCHAR(40),
    comprado         BOOLEAN       NOT NULL DEFAULT FALSE,
    created_by       BIGINT        NOT NULL,
    completed_by     BIGINT,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_shopping_items_list FOREIGN KEY (shopping_list_id)
        REFERENCES shopping_lists (id) ON DELETE CASCADE,
    CONSTRAINT fk_shopping_items_created_by FOREIGN KEY (created_by)
        REFERENCES users (id),
    CONSTRAINT fk_shopping_items_completed_by FOREIGN KEY (completed_by)
        REFERENCES users (id)
);

CREATE INDEX ix_shopping_items_list_id ON shopping_items (shopping_list_id);
CREATE INDEX ix_shopping_items_list_comprado ON shopping_items (shopping_list_id, comprado);

-- -------------------------------------------------------------------------------------
-- reading_entries — leituras por usuário (ownership).
-- nota NULLABLE com CHECK 1..5; CHECK data_fim >= data_inicio. Datas puras como DATE.
-- -------------------------------------------------------------------------------------
CREATE TABLE reading_entries (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL,
    titulo      VARCHAR(200)  NOT NULL,
    autor       VARCHAR(120),
    status      VARCHAR(20)   NOT NULL,
    nota        INT,
    data_inicio DATE,
    data_fim    DATE,
    observacoes VARCHAR(2000),
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_reading_entries_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_reading_entries_nota CHECK (nota IS NULL OR (nota BETWEEN 1 AND 5)),
    CONSTRAINT ck_reading_entries_datas CHECK (
        data_inicio IS NULL OR data_fim IS NULL OR data_fim >= data_inicio
    )
);

CREATE INDEX ix_reading_entries_user_status ON reading_entries (user_id, status);
